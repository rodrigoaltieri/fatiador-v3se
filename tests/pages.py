"""Teste da versão do GitHub Pages no Chrome: perfil inicial, fatiar sem CDN, baixar .gcode, exportar ajustes.
Uso: (na raiz) python3 -m http.server 8765 &  depois  python3 tests/pages.py [caminho do chrome]"""
import asyncio, re, sys, os
from playwright.async_api import async_playwright
URL = os.environ.get('URL', 'http://localhost:8765/index.html')
async def main():
    async with async_playwright() as p:
        kw = {'args': ['--use-gl=swiftshader', '--enable-unsafe-swiftshader']}
        if len(sys.argv) > 1: kw['executable_path'] = sys.argv[1]
        b = await p.chromium.launch(**kw)
        ctx = await b.new_context(viewport={'width': 1180, 'height': 820}, accept_downloads=True)
        ext = []
        async def block(r): ext.append(r.request.url); await r.abort()
        await ctx.route(re.compile(r'^https?://(?!localhost)'), block)
        logs = []
        pg = await ctx.new_page()
        pg.on('console', lambda m: logs.append(m.type + ': ' + m.text) if m.type == 'error' and 'GL Driver' not in m.text else None)
        pg.on('pageerror', lambda e: logs.append('PAGEERR ' + str(e)))
        await pg.goto(URL); await pg.wait_for_timeout(1200)
        print('perfil:', await pg.input_value('#f-tNozzle'), await pg.input_value('#f-maxVol'), '|', await pg.inner_text('#sync-note'))
        print('botão:', await pg.inner_text('#dl-zip'), '| txt visível:', await pg.is_visible('#dl-txt'))
        async def wait_slice():
            for _ in range(80):
                await pg.wait_for_timeout(500)
                st = await pg.inner_text('#status')
                if st.startswith('G-code pronto') or st.startswith('Falhou'): return st
            return 'TIMEOUT: ' + await pg.inner_text('#status')
        await pg.click('#ex-benchy')
        for _ in range(40):
            await pg.wait_for_timeout(250)
            st = await pg.inner_text('#status')
            if not st.startswith('Baixando'): break
        print('benchy:', st, '|', await pg.inner_text('#hud'))
        await pg.reload(); await pg.wait_for_timeout(1200)
        await pg.click('#ex-cyl'); await pg.wait_for_timeout(200)
        await pg.click('#go'); print('fatiar:', await wait_slice(), '|', await pg.inner_text('#r-time'))
        async with pg.expect_download() as d: await pg.click('#dl-zip')
        dl = await d.value; path = await dl.path(); txt = open(path, encoding='utf8').read()
        print('download:', dl.suggested_filename, len(txt), 'bytes |', 'M205 J0.100' in txt, '| M104 S205' in txt or 'S205' in txt)
        async with pg.expect_download() as d2: await pg.evaluate("document.getElementById('export-cfg').click()")
        print('exportar:', (await d2.value).suggested_filename)
        # a calibração fica atrás de "Recalibrar" (dentro de Avançado) e tem botão de voltar
        await pg.evaluate("document.querySelector('details.sec').open = true")
        await pg.click('#recal'); await pg.wait_for_timeout(300)
        print('recalibrar abre a calibração:', await pg.is_visible('#calib'), '| ajustes escondidos:', not await pg.is_visible('#settings'))
        async with pg.expect_download() as d3: await pg.click('#dl-orca')
        dl3 = await d3.value; t3 = open(await dl3.path(), encoding='utf8').read()
        print('cubo do Orca:', dl3.suggested_filename, len(t3), 'bytes |', 'generated by OrcaSlicer' in t3)
        # STL binário inteiro e o mesmo arquivo cortado (cabeçalho promete 12 triângulos, vêm 10): tem de avisar
        import struct, tempfile
        v = [(0,0,0),(20,0,0),(20,20,0),(0,20,0),(0,0,20),(20,0,20),(20,20,20),(0,20,20)]
        f = [(0,2,1),(0,3,2),(4,5,6),(4,6,7),(0,1,5),(0,5,4),(1,2,6),(1,6,5),(2,3,7),(2,7,6),(3,0,4),(3,4,7)]
        body = b''.join(struct.pack('<12fH', 0, 0, 0, *v[a], *v[b], *v[c], 0) for a, b, c in f)
        tmp = tempfile.mkdtemp()
        open(tmp + '/inteiro.stl', 'wb').write(b'\0' * 80 + struct.pack('<I', 12) + body)
        open(tmp + '/cortado.stl', 'wb').write(b'\0' * 80 + struct.pack('<I', 12) + body[:10 * 50 + 18])
        for nome in ('inteiro', 'cortado'):
            await pg.set_input_files('#file', tmp + '/' + nome + '.stl'); await pg.wait_for_timeout(600)
            print('stl ' + nome + ':', await pg.inner_text('#status'))
        await pg.click('#cal-back'); await pg.wait_for_timeout(200)
        # "Restaurar perfil" tem de trazer o perfil calibrado (perfil-inicial.json), não os valores de fábrica
        await pg.fill('#f-holeComp', '0,3'); await pg.dispatch_event('#f-holeComp', 'change')
        await pg.fill('#f-acc-outer', '700'); await pg.dispatch_event('#f-acc-outer', 'change')
        await pg.click('#reset-cfg'); await pg.wait_for_timeout(600)
        import json as _json
        async with pg.expect_download() as d4: await pg.evaluate("document.getElementById('export-cfg').click()")
        j4 = _json.load(open(await (await d4.value).path()))
        print('restaurar perfil:', await pg.inner_text('#status'), '| furos', j4['cfg']['holeComp'], '| XY', j4['cfg']['xyComp'], '| acel. externa', j4['cfg']['acc']['outer'], '| resultados', len(j4['cal']))
        print('externo bloqueado:', ext or 'nenhum')
        print('\n'.join(logs) or 'sem erros no console')
        await b.close()
asyncio.run(main())
